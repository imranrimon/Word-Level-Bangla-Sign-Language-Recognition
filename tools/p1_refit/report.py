#!/usr/bin/env python
"""Render docs/p1_refit_2026-10/RESULTS.md from refit_results.json (tools/p1_refit/refit.py).

  python tools/p1_refit/report.py --json docs/p1_refit_2026-10/refit_results.json --md docs/p1_refit_2026-10/RESULTS.md
"""
import argparse, hashlib, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def ci(x, f="{:+.2f}"):
    return f"[{f.format(x[0])}, {f.format(x[2])}]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=os.path.join(ROOT, "docs/p1_refit_2026-10/refit_results.json"))
    ap.add_argument("--md", default=os.path.join(ROOT, "docs/p1_refit_2026-10/RESULTS.md"))
    ap.add_argument("--extra", help="markdown file appended verbatim (notes / deviations)")
    a = ap.parse_args()
    R = json.load(open(a.json))
    pre = os.path.join(ROOT, "docs/p1_refit_2026-10/PREREG.md")
    h = hashlib.sha256(open(pre, "rb").read()).hexdigest()
    L = []
    w = L.append
    w("# P1 distance-gating law — pre-registered 7-pretraining-seed refit: RESULTS\n")
    w(f"Generated by `tools/p1_refit/refit.py` (json: `{os.path.relpath(a.json, ROOT)}`) and `tools/p1_refit/report.py`.")
    prov = os.path.join(ROOT, "docs/p1_refit_2026-10/PROVENANCE.md")
    redacted = h != R["prereg_sha256"] and os.path.exists(prov) and h in open(prov).read()
    status = "UNCHANGED" if h == R["prereg_sha256"] else (
        "UNCHANGED apart from the documented job-ID redaction (PROVENANCE.md)" if redacted else "CHANGED (!)")
    w(f"Pre-registration: `docs/p1_refit_2026-10/PREREG.md`, sha256 recorded `{R['prereg_sha256'][:16]}…`, "
      f"current file `{h[:16]}…` → **{status}**.\n")
    D = R["decision"]; P = R["primary"]
    w("## Verdict\n")
    w(f"**{D['verdict']}**\n")
    w(f"* D1 — P(b<0) = **{D['D1_P_b_neg']:.3f}** (threshold > 0.95) → {'PASS' if D['D1_pass'] else 'FAIL'}. "
      f"b posterior median {P['b'][1]:+.2f} pp/MMD, 95% CrI {ci(P['b'])} "
      f"({'excludes' if P['b_CI_excludes_0'] else 'includes'} 0).")
    w(f"* D2 — leave-one-language-out sign accuracy on pseed-pooled G = **{D['D2_lolo_correct']}/7** (threshold ≥ 6/7) → "
      f"{'PASS' if D['D2_pass'] else 'FAIL'}.")
    w(f"* Data: pretraining seeds {R['pseeds']}; seeds with all 7 languages complete: {R['pseeds_complete_all7']}; "
      f"{P['n_cells']} (language, pseed) cells; {len(R['exclusions'])} run-level exclusions/missing (listed below).\n")
    w("**Caveat on the x-axis (added after the pre-registration, from the code audit).** The pre-registered d_l are "
      "P1's canonical one-pass MMDs. The audit found they are computed against the wrong source: 400 WLASL + 400 BdSLW60-pretrain "
      "clips, whereas the real pool is BdSLW401 51,098 + WLASL 21,083 + BdSLW102a 3,408, with no BdSLW60. The audit also found "
      "that the WLASL pose cache inside every pool/xling backbone has a scrambled skeleton. The pre-registered verdict is "
      "therefore a measurement of the backbones that were actually run, against the paper's (flawed) distances. The "
      "real-pool-distance sensitivity below is NOT pre-registered.\n")

    w("## Primary model posterior (pseeds as above; Half-Normal(5) σ priors)\n")
    w("| quantity | median | 95% CrI |\n|---|---|---|")
    w(f"| intercept a (pp) | {P['a'][1]:+.2f} | {ci(P['a'])} |")
    w(f"| slope b (pp per unit MMD) | {P['b'][1]:+.2f} | {ci(P['b'])} |")
    for k, lab in (("sigma_u", "σ_u (shared pretraining-seed effect)"), ("sigma_v", "σ_v (language lack-of-fit)"),
                   ("sigma_w", "σ_w (language × pseed)")):
        w(f"| {lab} | {P[k][1]:.2f} | {ci(P[k], '{:.2f}')} |")
    w(f"| fine-tune noise √s̄² (plug-in, per cell) | {P['s2bar'] ** 0.5:.2f} | — |")
    w(f"| ICC_shared = σ_u²/total | {P['ICC_shared'][1]:.2f} | {ci(P['ICC_shared'], '{:.2f}')} |")
    w(f"| ICC_pseed = (σ_u²+σ_w²)/total | {P['ICC_pseed'][1]:.2f} | {ci(P['ICC_pseed'], '{:.2f}')} |")
    if P.get("dstar_given_bneg"):
        w(f"| d* = −a/b, conditional on b<0 | {P['dstar_given_bneg'][1]:.3f} | {ci(P['dstar_given_bneg'], '{:.3f}')} |")
    w("")
    w("Posterior predictive P(G < 0 | d):\n")
    w("| d | E[a+b·d] | P(line<0) | P(pseed-averaged G<0) (adds v*) | P(single new pretraining run G<0) |\n|---|---|---|---|---|")
    for d, v in P["P_G_neg"].items():
        w(f"| {d} | {v['mean']:+.2f} | {v['line']:.2f} | {v['pseed_avg']:.2f} | {v['single_run']:.2f} |")
    w("")
    w("## Leave-one-language-out (D2)\n")
    w("| held-out | d | predicted a+b·d (fit on other 6) | observed pseed-pooled G | sign correct |\n|---|---|---|---|---|")
    for t, v in R["lolo"].items():
        w(f"| {t} | {R['dist'][R['targets'].index(t)]:.3f} | {v['pred']:+.2f} | {v['obs']:+.2f} | {'yes' if v['correct'] else 'no'} |")
    w("")
    w("## Pre-registered sensitivity analyses (do not change the verdict)\n")
    w("| analysis | P(b<0) | b median [95% CrI] | LOLO sign |\n|---|---|---|---|")
    w(f"| primary | {P['P_b_neg']:.3f} | {P['b'][1]:+.2f} {ci(P['b'])} | {D['D2_lolo_correct']}/7 |")
    for k, lab in (("S1_no_collapse_exclusion", "S1 no collapse/gross exclusions"), ("S2_ftseeds_012", "S2 fine-tune seeds 0–2 only"),
                   ("S3_no_v", "S3 requested model (σ_v ≡ 0)"), ("S4a_hn10", "S4a σ ~ HalfNormal(10)"),
                   ("S4b_hc2.5", "S4b σ ~ HalfCauchy(2.5)"), ("S4c_b100", "S4c b ~ N(0,100²)")):
        if k in R:
            v = R[k]; lc = v.get("lolo_correct")
            w(f"| {lab} | {v['P_b_neg']:.3f} | {v['b'][1]:+.2f} {ci(v['b'])} | {'' if lc is None else f'{lc}/7'} |")
    if "replication_only_excl_ps0" in R:
        v = R["replication_only_excl_ps0"]; lc = sum(x["correct"] for x in v["lolo"].values())
        w(f"| replication only (pseeds {v['pseeds']}, drops hypothesis-generating ps0) | {v['P_b_neg']:.3f} | {v['b'][1]:+.2f} {ci(v['b'])} | {lc}/7 |")
    m = R.get("mixedlm", {})
    if "b" in m:
        w(f"| MixedLM REML (crossed pseed + language VCs), Wald | p={m['p']:.3f} (two-sided) | {m['b']:+.2f} [{m['ci'][0]:+.2f}, {m['ci'][1]:+.2f}] | — |")
        w(f"\nMixedLM variance components: {', '.join(f'{k} {v:.2f}' for k, v in m['vc'].items())}; residual (w+ε) {m['resid']:.2f} (pp²).")
    elif m:
        w(f"| MixedLM | error: {m.get('error')} | | |")
    w("")
    if "alt_dist" in R:
        w("## NOT pre-registered: real-pool distances (requested by the code audit)\n")
        w("x-axis recomputed by `tools/p1_refit/realpool_dist.py`: source = uniform (hence proportional) 800-clip draws from "
          "`data/ssl_pool_manifest_bdsl_asl.json` (the pool the backbones were actually pretrained on), same per-joint-speed "
          "descriptor and median-bandwidth RBF-MMD, 400 target train clips, mean of 3 pool draws. `masked` additionally drops "
          "MediaPipe dropout (zero) keypoints before differencing. Same primary model, priors, and LOLO rule.\n")
        langs = R["targets"]
        w("| x-axis | " + " | ".join(langs) + " | P(b<0) | b median [95% CrI] | LOLO sign |\n|---|" + "---|" * (len(langs) + 3))
        w("| paper canonical (pre-registered) | " + " | ".join(f"{d:.3f}" for d in R["dist"]) +
          f" | {P['P_b_neg']:.3f} | {P['b'][1]:+.2f} {ci(P['b'])} | {D['D2_lolo_correct']}/7 |")
        for k, v in R["alt_dist"].items():
            w(f"| {k} | " + " | ".join(f"{v['dist'][t]:.3f}" for t in langs) +
              f" | {v['P_b_neg']:.3f} | {v['b'][1]:+.2f} {ci(v['b'])} | {v['lolo_correct']}/7 |")
        w("")
    X = R.get("descriptive")
    if X:
        ps = R["pseeds"]
        w("## Descriptive: per-language G = xling − pool (VAL @10%, pp)\n")
        w("| target | d | " + " | ".join(f"ps{p}" for p in ps) + " | pooled | 95% hier CI | P(G>0) | SD over pseeds | pool / xling mean |")
        w("|---|---|" + "---|" * len(ps) + "---|---|---|---|---|")
        for t, v in X["per_lang"].items():
            cells = " | ".join("—" if g is None else f"{g:+.2f}" for g in v["per_pseed"])
            w(f"| {t} | {v['d']:.3f} | {cells} | **{v['pooled']:+.2f}** | [{v['ci'][0]:+.2f}, {v['ci'][1]:+.2f}] | {v['P_pos']:.2f} | "
              f"{v['sd_over_pseeds']:.2f} | {v['pool_mean']:.2f} / {v['xling_mean']:.2f} |")
        w("")
        w("Per-pretraining-seed 7-language OLS (as P1 reported for seed 0):\n")
        w("| pseed | slope(7) | R²(7) | paper-protocol sign |\n|---|---|---|---|")
        for p, v in X["per_pseed"].items():
            w(f"| {p} | {v['b7']:+.2f} | {v['r2_7']:.3f} | {v['sign_paper']}/7 |")
        if "pooled_ols" in X:
            o = X["pooled_ols"]
            w(f"\nPooled-mean OLS (P1's estimator applied to pooled G): all-7 {o['a7']:+.2f} {o['b7']:+.2f}·d, R² {o['r2_7']:.3f}; "
              f"calib-5 {o['a5']:+.2f} {o['b5']:+.2f}·d, R² {o['r2_5']:.3f}, LOO MAE(5) {o['loo5']:.2f}; paper-protocol sign "
              f"{o['sign_paper']}/7; Spearman ρ(7) {o['rho7']:+.2f}; frozen paper gate (d*=0.193) {X['frozen_gate_d0.193']}/7. "
              "(P1: R² 0.887 / 0.997, 7/7.)\n")
        w("## Held-out TEST G = xling − pool (P1 tab:test languages; fine-tune seeds 0–2)\n")
        w("| target | n pseeds | pool | xling | pooled G | 95% hier CI | P(G>0) |\n|---|---|---|---|---|---|---|")
        for t, v in X["test"].items():
            w(f"| {t} | {v['n_pseeds']} | {v['pool']:.2f} | {v['xling']:.2f} | **{v['pooled']:+.2f}** | [{v['ci'][0]:+.2f}, {v['ci'][1]:+.2f}] | {v['P_pos']:.2f} |")
        w("")
    B = R.get("bdsl_headline")
    if B:
        w("## BdSLW60 headline (P1 tab:sig / tab:test): pooled gains with hierarchical CI\n")
        w("Two-level bootstrap (pseeds within arm, then fine-tune seeds; arms unpaired; 20k). Mono exists for pseeds 0–2 only.\n")
        w("| split | contrast | n pseeds (arm1/arm2) | arm means | estimate | 95% CI | P(≤0) |\n|---|---|---|---|---|---|---|")
        for split in ("val", "test"):
            for k, v in B[split].items():
                if v:
                    w(f"| {split.upper()} | {k} | {v['n_pseeds'][0]}/{v['n_pseeds'][1]} | {v['arm_means'][0]:.2f} / {v['arm_means'][1]:.2f} | "
                      f"**{v['est']:+.2f}** | [{v['ci'][0]:+.2f}, {v['ci'][1]:+.2f}] | {v['P_le0']:.2f} |")
        w("\n(P1 reported xling−mono +4.2 VAL / +3.9 TEST and mono−scratch +4.8 VAL, all from pretraining seed 0.)\n")
    if R.get("baseline_refit_stdout"):
        w("## tab:transfer / tab:robust refit against pooled G (`tools/p1_law_baseline_refit.py`, verbatim)\n")
        w(R["baseline_refit_stdout"])
    w("## Exclusions / missing runs\n")
    if R["exclusions"]:
        w("| lang | pseed | arm | ft seed | reason | VAL |\n|---|---|---|---|---|---|")
        for e in R["exclusions"]:
            w(f"| {e['lang']} | {e['pseed']} | {e['arm']} | {e['ft_seed']} | {e['reason']} | {e['val']} |")
    else:
        w("None.")
    w("")
    if a.extra and os.path.exists(a.extra):
        w(open(a.extra).read())
    open(a.md, "w").write("\n".join(L) + "\n")
    print(f"[md] {a.md}")


if __name__ == "__main__":
    main()
